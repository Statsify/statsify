import { colors, panel, type } from "../src/index.ts";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const kebab = (name: string) => name.replaceAll(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

const theme: string[] = [];

for (const [name, hex] of Object.entries(colors.minecraft)) theme.push(`--color-mc-${kebab(name)}: ${hex};`);

for (const group of ["blueify", "redify", "blackify", "discord"] as const) {
  for (const [step, value] of Object.entries(colors[group])) theme.push(`--color-${group}-${step}: ${value};`);
}

theme.push(`--font-minecraft: ${type.families.minecraft};`, `--font-sans: ${type.families.sans};`);

for (const size of type.scale) theme.push(`--text-${size}: ${size}px;`);

// The card panel's look, for the site's boxes: plain variables, not theme ones, since no utility is made from them.
const root = [
  `--panel-background: ${panel.background};`,
  `--panel-bevel: ${panel.bevel}px;`,
  `--panel-shadow: rgb(0 0 0 / ${panel.shadowOpacity});`,
  `--panel-overlay: linear-gradient(180deg, ${panel.overlay.from} 0%, ${panel.overlay.to} 100%);`,
];

const indent = (lines: string[]) => lines.map((line) => `  ${line}`).join("\n");

const css = `/* Generated by packages/tokens/scripts/tokens-css.ts from src/index.ts. Do not edit. */

@theme {
${indent(theme)}
}

:root {
${indent(root)}
}
`;

const dist = join(import.meta.dirname, "..", "dist");
mkdirSync(dist, { recursive: true });
writeFileSync(join(dist, "tokens.css"), css);
